def _surface_phrase_pattern(phrase: str) -> re.Pattern[str]:
    casefold_phrase = phrase.casefold()
    pattern = re.escape(casefold_phrase)
    if casefold_phrase[0].isalnum():
        pattern = rf"(?<!\w){pattern}"
    if casefold_phrase[-1].isalnum():
        pattern = rf"{pattern}(?!\w)"
    return re.compile(pattern)


